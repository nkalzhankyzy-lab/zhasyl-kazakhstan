export type LayerPattern = "salt" | "crust" | "crack" | "sand" | "gypsum" | "roots" | "shells" | "gley" | "layers" | "plain";

export interface SoilLayer {
  /** Тереңдігі, см */
  from: number;
  to: number;
  name: string;
  text: string;
  color: string;
  pattern: LayerPattern;
}

