/** 1:5 сүзіндінің ЭӨ-сі бойынша шамамен топтау, мСм/см (саздақ топыраққа жуық бағдар) */
export const EC_CLASSES: { max: number; level: SalinityLevel }[] = [
  { max: 0.4, level: 0 },
  { max: 0.8, level: 1 },
  { max: 1.6, level: 2 },
  { max: 3.2, level: 3 },
  { max: Infinity, level: 4 },
];
export const salinityFromEc = (ec: number): SalinityLevel => EC_CLASSES.find((c) => ec < c.max)!.level;

export interface SoilPlace {
  id: string;
  name: string;
  short: string;
  /** Бойлық, ендік */
  at: [number, number];
  soil: string;
  salinity: SalinityLevel;
  /** 1:5 сүзінді ЭӨ, мСм/см — жоғарғы қабат, шамамен */
  ec: [number, number];
  ph: [number, number];
  /** Грунт суының тереңдігі, см (жоқ болса — 120 см-ден терең) */
  water: number | null;
  layers: SoilLayer[];
  why: string;
  plants: string[];
  tip: string;
}

